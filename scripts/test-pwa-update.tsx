import assert from 'node:assert/strict';
import React from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
// Compile the production-only branch to exercise worker replacement feedback.
mkdirSync('tmp/tests',{recursive:true});
await build({entryPoints:['src/components/PwaControls.tsx'],outfile:'tmp/tests/pwa-controls.mjs',bundle:true,format:'esm',platform:'node',external:['react'],define:{'import.meta.env.PROD':'true'}});
const {PwaControls}=await import(pathToFileURL(process.cwd()+'/tmp/tests/pwa-controls.mjs').href);
Object.assign(globalThis,{IS_REACT_ACT_ENVIRONMENT:true});
let reloads=0,confirmations=0;
const callbacks=new Map<string,Function>();
const registration={active:{},waiting:null,installing:null,addEventListener(){},removeEventListener(){}};
const serviceWorker={controller:{},ready:Promise.resolve(registration),register:async()=>registration,addEventListener:(type:string,fn:Function)=>callbacks.set(type,fn),removeEventListener:(type:string)=>callbacks.delete(type)};
Object.defineProperty(globalThis,'navigator',{configurable:true,value:{onLine:true,serviceWorker}});
Object.assign(globalThis,{window:{matchMedia:()=>({matches:false}),isSecureContext:true,addEventListener(){},removeEventListener(){},location:{reload(){reloads++;}}},confirm:()=>{confirmations++;return true;}});
let view:ReactTestRenderer;
const text=(node:any):string=>typeof node==='string'?node:(node.children??[]).map(text).join('');
await act(async()=>{view=create(<PwaControls/>);await new Promise(resolve=>setTimeout(resolve,0));});
assert.ok(!view!.root.findAllByType('button').some(button=>text(button).startsWith('Update available')));
await act(async()=>{callbacks.get('controllerchange')!();});
const refresh=view!.root.findAllByType('button').find(button=>text(button).startsWith('Update available'));
assert.ok(refresh,'An already controlled open session must offer refresh after automatic worker replacement');
assert.equal(reloads,0,'Never discard unsaved edits automatically');
await act(async()=>{refresh.props.onClick();});
assert.equal(confirmations,1);assert.equal(reloads,1);
await act(async()=>view.unmount());
assert.ok(!callbacks.has('controllerchange'));
console.log('PASS installed-app update: automatic worker replacement offers refresh, waits for user confirmation, reloads the new app, and cleans up listeners');
